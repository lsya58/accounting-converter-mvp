def field_retention(variant: FreeeJournalVariant, column: str, *, value_unobserved: bool = False,
                    display_name_differs: bool = False) -> tuple[RetentionStatus, str]:
    """(status, reason) of one freee column on the way to JDL. Unknown columns and unobserved values are
    MEANING_UNCONFIRMED whatever their name suggests."""
    role = COLUMN_ROLES.get(variant, {}).get(column)
    if role is None:
        return RetentionStatus.MEANING_UNCONFIRMED, "UNKNOWN_SOURCE_COLUMN"
    if value_unobserved:
        return RetentionStatus.MEANING_UNCONFIRMED, "VALUE_UNOBSERVED"
    if role.role is Role.ACCOUNT_DISPLAY_NAME and display_name_differs:
        return RetentionStatus.MEANING_UNCONFIRMED, "ACCOUNT_DISPLAY_NAME_DIFFERS"
    if role.role in _ROLE_RETENTION:
        return _ROLE_RETENTION[role.role]
    klass = information_class(column)
    return _CLASS_RETENTION[klass], klass


@dataclass(frozen=True)
class FreeeJournalResult:
    """One journal of the file, located by file-local numbers only (no freee ID, account, amount or text)."""
    display_number: str
    rows: tuple[int, ...]  # parsed: every row of the journal; rejected: the rows where a problem was found
    parsed: bool
    reasons: tuple[str, ...]  # blockers (parsed) or FreeeIssue codes (rejected), sorted
    shape: tuple[int, int, int] | None = None
    closing: bool = False
    compound: bool = False

    def to_dict(self) -> dict:
        return {
            "display_number": self.display_number, "rows": list(self.rows), "parsed": self.parsed,
            "reasons": list(self.reasons), "shape": None if self.shape is None else "{}D{}C/{}rows".format(*self.shape),
            "closing": self.closing, "compound": self.compound,
        }


@dataclass(frozen=True)
class FreeeTaxHint:
    """What the freee tax NAME suggests. A hint for the Human, never a mapping."""
    kind: str  # SALES_TAXABLE / PURCHASE_TAXABLE / NON_TAXABLE_SALES / NON_TAXABLE_PURCHASE / EXPORT_SALES / OUT_OF_SCOPE / UNKNOWN
    rate: str | None = None  # "10" / "8"
    reduced: bool = False
    deduction_ratio: str | None = None  # 経過措置 "80" / "50" / "30" ...
    allocation: str | None = None  # 個別対応: 課税売上対応 / 共通対応 / 非課税売上対応

    @property
    def taxed(self) -> bool:
        return self.kind in {"SALES_TAXABLE", "PURCHASE_TAXABLE"}


_RATE = re.compile(r"(10|8)%")
_DEDUCTION = re.compile(r"控(\d{2})")


def tax_hint(name: str | None) -> FreeeTaxHint:
    if not name:
        return FreeeTaxHint("OUT_OF_SCOPE")
    rate_match = _RATE.search(name)
    rate = rate_match.group(1) if rate_match else None
    reduced = "軽" in name
    deduction = _DEDUCTION.search(name)
    if name in {"対象外", "不課税"}:
        return FreeeTaxHint("OUT_OF_SCOPE")
    if name.startswith("輸出"):
        return FreeeTaxHint("EXPORT_SALES")
    if name.startswith("非課売上"):
        return FreeeTaxHint("NON_TAXABLE_SALES")
    if name.startswith("非課仕入"):
        return FreeeTaxHint("NON_TAXABLE_PURCHASE")
    if name.startswith("課税売上"):
        return FreeeTaxHint("SALES_TAXABLE", rate, reduced)
    for prefix, allocation in (("課対仕入", "課税売上対応"), ("共対仕入", "共通対応"), ("非対仕入", "非課税売上対応")):
        if name.startswith(prefix):
            return FreeeTaxHint(
                "PURCHASE_TAXABLE", rate, reduced, deduction.group(1) if deduction else None,
                allocation if prefix != "課対仕入" else None,
            )
    return FreeeTaxHint("UNKNOWN", rate, reduced)


@dataclass
class FreeeDiagnosis:
    parse: FreeeParseResult
    direction_stage: str
    ready_allowed: bool
    journal_blockers: dict[str, tuple[str, ...]] = field(default_factory=dict)
    tax_categories: Counter = field(default_factory=Counter)
    information_fields: Counter = field(default_factory=Counter)  # column -> journals
    shapes: Counter = field(default_factory=Counter)
    shapes_with_jdl_row_evidence: int = 0
    tax: Counter = field(default_factory=Counter)  # explicit / zero / blank / absent tax amounts, by line
    tax_inclusion_raw: Counter = field(default_factory=Counter)  # 内税・外税 value -> lines (product vocabulary)
    tax_accounting_methods: Counter = field(default_factory=Counter)  # 消費税経理処理方法 -> journals
    structure: Counter = field(default_factory=Counter)
    blank_sides: Counter = field(default_factory=Counter)  # representation -> sides
    closing: Counter = field(default_factory=Counter)
    unobserved_value_columns: Counter = field(default_factory=Counter)  # column -> journals
    retention: RetentionInventory = field(default_factory=RetentionInventory)
    journals: list[FreeeJournalResult] = field(default_factory=list)  # file order: parsed and rejected

    @property
    def journals_read(self) -> int:
        """Journals found in the file (parsed + rejected). 0 when the file itself could not be read."""
        return len(self.parse.entries) + self.parse.rejected_journals if self.parse.file_readable else 0

    @property
    def journals_parsed(self) -> int:
        return len(self.parse.entries) if self.parse.file_readable else 0

    @property
    def journals_rejected(self) -> int:
        return self.parse.rejected_journals if self.parse.file_readable else 0

    @property
    def file_issues(self) -> tuple[str, ...]:
        return tuple(dict.fromkeys(i.code.value for i in self.parse.issues if i.code in FILE_LEVEL_ISSUES))

    @property
    def formal_ready(self) -> int:
        """Always 0 today. Kept computed (not a constant) so the guard is visible and tested."""
        if not self.ready_allowed:
            return 0
        return sum(1 for blockers in self.journal_blockers.values() if not blockers)

    def to_dict(self) -> dict:
        header = self.parse.header
        blockers = Counter(code for codes in self.journal_blockers.values() for code in codes)
        return {
            "direction": DIRECTION_KEY,
            "direction_stage": self.direction_stage,
            "ready_allowed": self.ready_allowed,
            "formal_ready": self.formal_ready,
            "evidence_id": EVIDENCE_ID,
            "format": None if header is None else {
                "variant": header.variant.value,
                "encoding": header.encoding,
                "newline": header.newline,
                "header_fingerprint": header.fingerprint,
                "header_observed": header.observed,
                "header_verified": header.verified,
                "columns": len(header.columns),
                "unknown_columns": list(header.unknown_columns),
                "missing_observed_columns": list(header.missing_observed_columns),
                "source_format_key": header.source_format_key,
            },
            "file_readable": self.parse.file_readable,
            "data_rows": self.parse.data_rows,
            "rows_accepted": self.parse.accepted_rows,
            "journals_parsed": len(self.parse.entries),
            "journals_rejected": self.parse.rejected_journals,
            "rows_rejected": self.parse.rejected_rows,
            "issues": dict(Counter(issue.code.value for issue in self.parse.issues)),
            "blockers": dict(sorted(blockers.items())),
            "tax_categories": {
                name or "(空欄)": {"lines": count, "hint": tax_hint(name).__dict__}
                for name, count in sorted(self.tax_categories.items(), key=lambda item: item[0] or "")
            },
            "tax_amounts": dict(sorted(self.tax.items())),
            "tax_inclusion_raw": dict(sorted(self.tax_inclusion_raw.items())),
            "tax_accounting_methods": dict(sorted(self.tax_accounting_methods.items())),
            "structure": dict(sorted(self.structure.items())),
            "blank_sides": dict(sorted(self.blank_sides.items())),
            "closing": dict(sorted(self.closing.items())),
            "unobserved_value_columns": dict(sorted(self.unobserved_value_columns.items())),
            "information_without_jdl_column": {
                column: {"journals": count, "class": information_class(column)}
                for column, count in sorted(self.information_fields.items())
            },
            "shapes": {f"{d}D{c}C/{r}rows": n for (d, c, r), n in sorted(self.shapes.items())},
            "journals_simple_1d1c_or_shape_with_jdl_row_evidence": self.shapes_with_jdl_row_evidence,
            "journals_read": self.journals_read,
            "file_issues": list(self.file_issues),
            "information_retention": {
                status.value: {
                    item.field: {"reason": item.reason, "journals": item.journals, "cells": item.values}
                    for item in items
                }
                for status, items in self.retention.by_status().items()
            },
            "journals": [journal.to_dict() for journal in self.journals],
        }


def journal_blockers(entry: JournalEntry, *, header_verified: bool, ready_allowed: bool, has_description: bool,
                     variant_known: bool = True, header_observed: bool = False) -> tuple[str, ...]:
    found: set[str] = {"HUMAN:ACCOUNT_MAPPING"}  # freee has no confirmed mapping store
    if not variant_known:
        found.add("SYSTEM_EVIDENCE:FREEE_VARIANT_UNKNOWN")
    if not header_observed:
        found.add("SYSTEM_EVIDENCE:FREEE_HEADER_NOT_OBSERVED")
    if not header_verified:
        found.add("SYSTEM_EVIDENCE:FREEE_SOURCE_FORMAT_UNVERIFIED")
    if not ready_allowed:
        found.add("SYSTEM_IMPLEMENTATION:DIRECTION_NOT_PRODUCTION")
    if not has_description:
        found.add("SYSTEM_EVIDENCE:FREEE_DESCRIPTION_SOURCE_UNKNOWN")
    # 税込経理 / 税抜経理 of the freee office vs the JDL company context: never assumed.
    if entry.metadata.get(TAX_ACCOUNTING_METHOD_KEY):
        found.add("SYSTEM_EVIDENCE:FREEE_TAX_ACCOUNTING_METHOD_UNMAPPED")
    else:
        found.add("HUMAN:FREEE_TAX_ACCOUNTING_METHOD_UNKNOWN")
    if entry.metadata.get(UNOBSERVED_VALUES_KEY):
        found.add("SYSTEM_EVIDENCE:FREEE_VALUE_UNOBSERVED")
    for line in entry.lines:
        info = line.tax_info
        hint = tax_hint(info.category if info is not None else None)
        if info is not None and info.category:
            found.add("HUMAN:TAX_MAPPING")
            if hint.kind == "UNKNOWN":
                found.add("SYSTEM_EVIDENCE:FREEE_TAX_CATEGORY_UNRECOGNISED")
        if info is not None:
            if hint.taxed:
                if info.metadata.get("freee_tax_inclusion_raw"):
                    found.add("SYSTEM_EVIDENCE:FREEE_TAX_INCLUSION_MAPPING_UNVERIFIED")  # 内税/外税 -> JDL 税入力方法
                else:
                    found.add("SYSTEM_EVIDENCE:FREEE_TAX_INCLUSION_UNKNOWN")
                if info.tax_amount is None:
                    found.add("SYSTEM_EVIDENCE:FREEE_TAX_AMOUNT_ABSENT")  # never computed
            elif info.tax_amount not in (None, 0):
                found.add("SYSTEM_EVIDENCE:FREEE_TAX_AMOUNT_ON_UNTAXED_CATEGORY")
            if info.rate is not None and (
                (hint.taxed and hint.rate is not None and info.rate != int(hint.rate))
                or (not hint.taxed and hint.kind != "UNKNOWN" and info.rate != 0)
            ):
                found.add("SYSTEM_EVIDENCE:FREEE_TAX_RATE_INCONSISTENT")
        if line.amount == 0:
            found.add("SYSTEM_EVIDENCE:FREEE_ZERO_AMOUNT_LINE_UNOBSERVED")
        if line.amount < 0 or (info is not None and info.tax_amount is not None and info.tax_amount < 0):
            found.add("HUMAN:NEGATIVE_AMOUNT")
        if line.department:
            found.add("HUMAN:DEPARTMENT_MAPPING")
        display = line.metadata.get("freee_account_display_name")
        if display and display != line.account:
            found.add("HUMAN:ACCOUNT_DISPLAY_NAME_DIFFERS")  # e.g. 受取利息 -> 事業主借: never replaced
    rows = journal_physical_rows(entry)
    if rows is None:
        found.add("SYSTEM_EVIDENCE:FREEE_ROW_DESCRIPTION_INCONSISTENT")  # 借方備考 != 貸方備考 in one row
    elif physical_row_shape(rows) not in OBSERVED_JOURNAL_SHAPES:
        found.add("SYSTEM_EVIDENCE:FREEE_JOURNAL_SHAPE_UNOBSERVED")
    for value in source_fields(entry):
        if not value.known:
            found.add("SYSTEM_EVIDENCE:UNKNOWN_SOURCE_COLUMN")
        elif information_class(value.field) == NEEDS_HUMAN_TRANSFORMATION:
            found.add("HUMAN:COUNTERPARTY_POLICY")
        elif information_class(value.field) == NO_JDL_COLUMN:
            found.add("HUMAN:NON_RETAINED_INFORMATION")
    if closing_adjustment_marker(entry) is not None:
        found.add("SYSTEM_EVIDENCE:FREEE_CLOSING_MARKER_UNVERIFIED")
    return tuple(sorted(found))


def diagnose_freee_journal_csv(path: Path) -> FreeeDiagnosis:
    return diagnose_parse_result(FreeeJournalCsvParser().parse_path(path))


def _has_description(variant: FreeeJournalVariant, columns: tuple[str, ...]) -> bool:
    roles = COLUMN_ROLES.get(variant, {})
    wanted = {Role.ROW_DESCRIPTION} if variant is FreeeJournalVariant.OLD_CSV else {Role.SIDE_DESCRIPTION}
    present = [name for name in columns if name in roles and roles[name].role in wanted]
    return len(present) == (1 if variant is FreeeJournalVariant.OLD_CSV else 2)


def diagnose_parse_result(parse: FreeeParseResult) -> FreeeDiagnosis:
    direction = direction_for(DIRECTION_KEY)
    diagnosis = FreeeDiagnosis(parse, direction.stage.value, direction.ready_allowed)
    header = parse.header
    if header is None or not parse.file_readable:
        return diagnosis
    has_description = _has_description(header.variant, header.columns)
    _rejected_journals(diagnosis)
    for entry in parse.entries:
        diagnosis.journal_blockers[entry.id] = journal_blockers(
            entry, header_verified=header.verified, ready_allowed=direction.ready_allowed,
            has_description=has_description, variant_known=header.variant is not FreeeJournalVariant.UNKNOWN,
            header_observed=header.observed,
        )
        for line in entry.lines:
            info = line.tax_info
            if info is None:
                diagnosis.tax["lines_without_tax_cells"] += 1
                continue
            diagnosis.tax_categories[info.category] += 1
            if not info.metadata.get("tax_amount_column_present"):
                diagnosis.tax["tax_amount_column_absent"] += 1
            elif info.tax_amount is None:
                diagnosis.tax["tax_amount_blank"] += 1
            elif info.tax_amount == 0:
                diagnosis.tax["tax_amount_explicit_zero"] += 1
            else:
                diagnosis.tax["tax_amount_explicit_nonzero"] += 1
            if info.metadata.get("freee_tax_inclusion_raw"):
                diagnosis.tax_inclusion_raw[info.metadata["freee_tax_inclusion_raw"]] += 1
        method = entry.metadata.get(TAX_ACCOUNTING_METHOD_KEY)
        diagnosis.tax_accounting_methods[method or "(列なし)"] += 1
        for _row, _side, representation in entry.metadata.get(BLANK_SIDES_KEY, ()):
            diagnosis.blank_sides[representation] += 1
        row_count = len(entry.metadata.get(ROW_ORDER_KEY, ()) or ())
        diagnosis.structure["journals"] += 1
        diagnosis.structure["compound_journals" if len(entry.lines) > 2 else "simple_journals"] += 1
        if row_count > 1:
            diagnosis.structure["multi_row_journals"] += 1
        if closing_adjustment_marker(entry) is not None:
            diagnosis.closing["closing_marker_journals"] += 1
        flag = entry.metadata.get(PERIOD_END_FLAG_KEY)
        if flag is not None:
            diagnosis.closing[f"period_end_flag={flag}"] += 1
        for column in entry.metadata.get(UNOBSERVED_VALUES_KEY, ()):
            diagnosis.unobserved_value_columns[column] += 1
        for column in {value.field for value in source_fields(entry) if value.known}:
            diagnosis.information_fields[column] += 1
        rows = journal_physical_rows(entry)
        shape = None
        if rows is not None:
            shape = physical_row_shape(rows)
            diagnosis.shapes[shape] += 1
            if shape in JDL_ROW_DESCRIPTION_VERIFIED_SHAPES or (shape[2] == 1 and shape[:2] == (1, 1)):
                diagnosis.shapes_with_jdl_row_evidence += 1
        _add_retention(diagnosis.retention, header.variant, entry)
        diagnosis.journals.append(FreeeJournalResult(
            display_number=str(entry.metadata.get(DISPLAY_NUMBER_KEY) or ""),
            rows=tuple(entry.metadata.get(ROW_ORDER_KEY, ()) or ()),
            parsed=True,
            reasons=diagnosis.journal_blockers[entry.id],
            shape=shape,
            closing=closing_adjustment_marker(entry) is not None,
            compound=len(entry.lines) > 2,
        ))
    diagnosis.journals.sort(key=lambda journal: journal.rows[:1] or (0,))
    return diagnosis


def _add_retention(inventory: RetentionInventory, variant: FreeeJournalVariant, entry: JournalEntry) -> None:
    unobserved = set(entry.metadata.get(UNOBSERVED_VALUES_KEY, ()) or ())
    differs = {
        "借方決算書表示名" if line.side.value == "DEBIT" else "貸方決算書表示名"
        for line in entry.lines
        if line.metadata.get("freee_account_display_name") not in (None, line.account)
    }
    for column, cells in entry.metadata.get(NONBLANK_COLUMNS_KEY, ()) or ():
        status, reason = field_retention(
            variant, column, value_unobserved=column in unobserved, display_name_differs=column in differs,
        )
        inventory.add(column, status, reason, journals=1, values=cells)


def _rejected_journals(diagnosis: FreeeDiagnosis) -> None:
    """Rejected journals, grouped by the file-local display number they were reported with (rows always counted)."""
    grouped: dict[tuple[str, int], set[str]] = {}
    rows: dict[tuple[str, int], set[int]] = {}
    order: list[tuple[str, int]] = []
    current: tuple[str, int] | None = None
    for issue in diagnosis.parse.issues:
        if issue.code in FILE_LEVEL_ISSUES:
            continue
        number = str(issue.journal_number or "")
        if current is None or current[0] != number or not number:
            current = (number, issue.row_number or 0)
            if current not in grouped:
                order.append(current)
        grouped.setdefault(current, set()).add(issue.code.value)
        if issue.row_number is not None:
            rows.setdefault(current, set()).add(issue.row_number)
    for key in order:
        diagnosis.journals.append(FreeeJournalResult(
            display_number=key[0], rows=tuple(sorted(rows.get(key, ()))), parsed=False,
            reasons=tuple(sorted(grouped[key])),
        ))
